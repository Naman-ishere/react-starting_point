// let, var and const --> The way to declare a variable, JS automatically determines the type;

// let --> the best way;

let name_ = "Naman";
let age = 17;
let isMature = false;

// var --> similar to let, but really weird, has scope issues;

var animal = "Cheetah";
var numberOfCheetahs = 45;
var isGoodAnimal = false;

// const --> Use this to assign variables whose values you don't want to change. EVER.

const pi = 3.14159;

