// Template Literal : Enhanced way to combine the variables numerical values and other things in string messages;

// How to use?? : 
// in a string --> Use backticks and then when you want to add a variable, use dollar sign and curly brackets

// Normal way : 
let name_ = "Naman"; 
console.log("My name is:", name_);

// Using template literal;
console.log(`My name is: ${name_}`);